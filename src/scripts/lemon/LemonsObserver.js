import { Lemon } from "./Lemon.js";

// ----------------------------------------------
// CLASS
// ----------------------------------------------

export class LemonsObserver
{
    // ----------------------------------------------
    // ATTRIBUTES
    // ----------------------------------------------

    #lemons = [];

    // ----------------------------------------------
    // CONSTRUCTOR
    // ----------------------------------------------

    constructor()
    {
    }

    // ----------------------------------------------
    // METHODS
    // ----------------------------------------------

    suscribe(lemon)
    {
        this.#lemons.push(lemon);
    }

    notify()
    {
        this.#lemons.forEach(lemon => lemon.onNotify());
    }
}